        const id = art.id || '';
        const featured = MASTERPIECE_FEATURED_STORIES[id];

        if (featured) {
            return {
                title: art.title,
                enTitle: art.enTitle || '',
                artist: art.artist,
                category: art.category,
                genre: art.genre,
                period: featured.period,
                location: featured.location,
                context: featured.context,
                appreciation: featured.appreciation,
                quote: art.quote || '',
                quoteAuthor: art.quoteAuthor || ''
            };
        }

