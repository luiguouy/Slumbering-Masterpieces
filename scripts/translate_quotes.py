def clean_key(s):
    # normalize quotes and whitespace
    s = s.strip()
    s = re.sub(r'^[“"\'`]+|[”"\'`]+$', '', s)
    return s.strip()

CLEAN_MAP = {clean_key(k): v for k, v in TRANSLATIONS.items()}

def get_zh(en_quote):
    if not en_quote:
        return ""
    ck = clean_key(en_quote)
    if ck in CLEAN_MAP:
        return CLEAN_MAP[ck]
    # fuzzy matching fallback
    for k, v in CLEAN_MAP.items():
        if k in ck or ck in k:
            return v
    return ""

def main():
    with open("quotes_all.json", "r", encoding="utf-8") as f:
        quotes = json.load(f)
    
    missing = []
    final_dict = {}
    for q in quotes:
        zh = get_zh(q)
        if zh:
            final_dict[q] = zh
        else:
            missing.append(q)
            
    print(f"Total quotes: {len(quotes)}")
    print(f"Matched: {len(final_dict)}")
    print(f"Missing: {len(missing)}")
    if missing:
        for m in missing[:10]:
            print("Missing:", m)
            
    with open("data/quote_translations.json", "w", encoding="utf-8") as f:
        json.dump(final_dict, f, ensure_ascii=False, indent=2)
    print("Saved data/quote_translations.json successfully!")

if __name__ == "__main__":
    main()
