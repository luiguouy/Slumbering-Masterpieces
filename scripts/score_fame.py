# 展厅内的次级排序权重（fame 相同时保持画派集中，不出现随机跳色）
CATEGORY_WEIGHT = {
    'renaissance': 8, 'baroque': 7, 'romanticism': 6,
    'realism': 5, 'monet': 4, 'impressionism': 3,
    'post_impressionism': 2, 'expressionism': 1,
}


def artist_default(artist):
    if artist in ARTIST_BASE:
        return ARTIST_BASE[artist]
    for key, score in ARTIST_BASE.items():
        if artist.startswith(key):
            return score
    return 45


def main():
    with open(DATA_PATH, 'r', encoding='utf-8') as f:
        content = f.read()
    m_items = re.search(r'window\.MASTERPIECES\s*=\s*(\[.*?\]);', content, re.DOTALL)
    m_cats = re.search(r'window\.ART_CATEGORIES\s*=\s*(\[.*?\]);', content, re.DOTALL)
    items = json.loads(m_items.group(1))
    categories = json.loads(m_cats.group(1))

    original_order = {p['id']: i for i, p in enumerate(items)}
    missing = []
    for p in items:
        if p['id'] in FAME and FAME[p['id']] > 0:
            p['fame'] = FAME[p['id']]
        else:
            p['fame'] = artist_default(p['artist'])
            missing.append(p['id'])

    items.sort(key=lambda p: (
        -p['fame'],
        -CATEGORY_WEIGHT.get(p['category'], 0),
        original_order[p['id']],
    ))

    header = (
        '/**\n * Slumbering Masterpieces · World Fine Art Collection\n'
        f' * 全球世界级传世名画博览馆数据库（共 {len(items)} 幅殿堂级油画旷世杰作，按知名度 fame 权重降序）\n */\n\n'
    )
    new_content = header
    new_content += 'window.ART_CATEGORIES = ' + json.dumps(categories, ensure_ascii=False, indent=4) + ';\n\n'
    new_content += 'window.MASTERPIECES = ' + json.dumps(items, ensure_ascii=False, indent=4) + ';\n'
    with open(DATA_PATH, 'w', encoding='utf-8') as f:
        f.write(new_content)

    print(f'已按知名度重排 {len(items)} 幅；逐幅精评 {len(items) - len(missing)} 幅，按画家基准分 {len(missing)} 幅')
    print('\n前 30 名：')
    for i, p in enumerate(items[:30], 1):
        print(f"  {i:3d}. [{p['fame']:3d}] {p['title']} — {p['artist']}")
    print('\n末位 10 名：')
    for i, p in enumerate(items[-10:], len(items) - 9):
        print(f"  {i:3d}. [{p['fame']:3d}] {p['title']} — {p['artist']}")


if __name__ == '__main__':
    main()
